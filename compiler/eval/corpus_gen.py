def generate(out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    for stale in out_dir.glob("*.c"):
        stale.unlink()

    written: list[Path] = []

    for cwe, slug, bad, g2b, b2g, needs_argc in TEMPLATES:
        for variant, (desc, template) in VARIANTS.items():
            parts = [HEADER.format(cwe=cwe, variant=variant, variant_desc=desc)]
            parts.append(_fn("bad", bad, template, needs_argc))
            parts.append(_fn("goodG2B", g2b, template, needs_argc))
            if b2g != g2b:
                parts.append(_fn("goodB2G", b2g, template, needs_argc))
            path = out_dir / f"{cwe}_{slug}__{variant}.c"
            path.write_text("\n".join(parts), encoding="utf-8")
            written.append(path)

    for cwe, slug, body in INTERPROCEDURAL:
        text = HEADER.format(
            cwe=cwe, variant="05", variant_desc="interprocedural: flow crosses a helper function"
        )
        # Each root gets its own helper chain so taint cannot leak between them.
        helpers = "\n".join(
            line.replace("{tag}", tag)
            for tag in ("bad", "goodG2B", "goodB2G")
            for line in body.splitlines()
            if line.startswith("static")
        )
        rest = "\n".join(line for line in body.splitlines() if not line.startswith("static"))
        path = out_dir / f"{cwe}_{slug}__05.c"
        path.write_text(text + "\n" + helpers + "\n" + rest, encoding="utf-8")
        written.append(path)

    return sorted(written)


