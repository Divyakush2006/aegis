"""Generate the paired evaluation corpus.

The corpus follows the NIST Juliet conventions so that the same harness scores
both this corpus and the real SARD test suite without modification:

* file name ``CWE<n>_<description>__<variant>.c`` carries the expected weakness;
* a function named ``bad*`` contains the flaw;
* functions named ``good*`` are the safe counterparts, in Juliet's two forms --
  ``goodG2B`` replaces the untrusted source with a safe value, ``goodB2G``
  keeps the source but fixes the sink.

Generating from templates is how Juliet is built too, and it is what makes the
*flow variant* axis meaningful: the same weakness is expressed through
increasingly indirect control and call structure, so the results table shows
where precision degrades rather than just whether the tool fires at all.

Run ``python eval/corpus_gen.py`` to regenerate. Output is deterministic.
"""
from __future__ import annotations

from pathlib import Path

HEADER = """/* Generated by eval/corpus_gen.py -- do not edit by hand.
 * Expected weakness: {cwe}
 * Flow variant {variant}: {variant_desc}
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

char *escape_shell(char *s);

/* Opaque to the analysis, so no variant is folded away as unreachable. */
extern int aegis_cond;
"""

#: Flow variants, mirroring the Juliet scheme. Each wraps a statement body in
#: progressively more indirect control or call structure.
VARIANTS: dict[str, tuple[str, str]] = {
    "01": ("baseline: source and sink in the same basic block", "{body}"),
    "02": (
        "control dependent: the flow runs through a conditional",
        "if (aegis_cond > 1) {{\n{body}\n    }}",
    ),
    "03": (
        "loop carried: the flow runs through a loop body",
        "{{ int _i; for (_i = 0; _i < 2; _i++) {{\n{body}\n    }} }}",
    ),
    "04": (
        "nested control: conditional inside a loop",
        "{{ int _i; for (_i = 0; _i < 2; _i++) {{ if (aegis_cond == _i) {{\n{body}\n    }} }} }}",
    ),
}


def _fn(name: str, body: str, variant_template: str, needs_argc: bool = True) -> str:
    indented = "\n".join("        " + line for line in body.strip().splitlines())
    wrapped = variant_template.format(body=indented)
    signature = "int argc, char **argv" if needs_argc else "void"
    return f"void {name}({signature})\n{{\n    {wrapped}\n}}\n"


